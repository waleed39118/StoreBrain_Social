"""Regenerate docs/schema.sql (SQLite DDL) from the ORM models: python scripts/dump_schema.py"""

from pathlib import Path

from sqlalchemy import create_mock_engine
from sqlalchemy.schema import CreateIndex, CreateTable

from atheer.db.models import Base

engine = create_mock_engine("sqlite://", executor=lambda *a, **k: None)
parts = ["-- Atheer SQLite schema. Generated by scripts/dump_schema.py — do not edit by hand.", "PRAGMA foreign_keys = ON;"]
for table in Base.metadata.sorted_tables:
    parts.append(str(CreateTable(table).compile(dialect=engine.dialect)).strip() + ";")
    parts += [str(CreateIndex(ix).compile(dialect=engine.dialect)).strip() + ";" for ix in sorted(table.indexes, key=lambda i: i.name)]
out = Path(__file__).resolve().parents[1] / "docs" / "schema.sql"
out.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
print(f"wrote {out}")
